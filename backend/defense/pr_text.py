"""Remediation PR description, with the proof-of-absence result attached.

Every figure comes from the verify() result; nothing is filled in by hand.
"""
from backend.defense.mincut import FixPlan


def remediation_markdown(plan: FixPlan, proof: dict) -> str:
    safe = proof["verified_safe"]
    status = ("**Verified safe: 0 attack paths remain.**" if safe
              else f"**Not fully fixed: {proof['paths_after']} path(s) remain.**")
    lines = [
        f"## Sever {plan.paths_before} agent attack path(s) in `{plan.stack}`", "",
        f"BlastRadius found **{plan.paths_before}** path(s) from untrusted input to a dangerous "
        f"sink (open risk **{plan.open_risk_before}**). This change applies the cheapest set of "
        f"fixes that cuts all of them.", "",
        "### Changes", "",
        "| Fix | Why | Cost | Paths severed |", "|---|---|---|---|",
    ]
    for f in plan.fixes:
        lines.append(f"| {f.describe()} | {_why(f)} | {f.cost} | {f.paths_severed} |")
    lines += [
        "", f"Total plan cost **{plan.plan_cost}** (gate = 1, scope = 3, remove tool = 10).", "",
        "### Why this is the minimum", "",
        f"The fix set is a minimum cut over the attack-path subgraph. networkx computes cut "
        f"value **{plan.cut_value:g}**; FalkorDB's own `algo.maxFlow` on the same network returns "
        f"**{plan.maxflow_falkordb:g}** ({plan.maxflow_ms} ms). They "
        f"{'agree' if abs((plan.maxflow_falkordb or 0) - plan.cut_value) < 1e-6 else 'DISAGREE'}.",
        "", "### Proof of absence", "",
        status, "",
        f"After applying the patch the same Cypher query (`paths_to_sinks`) was re-run on the "
        f"patched graph: **{proof['badge']}**.", "",
        f"- Paths before: {proof['paths_before']} (risk {proof['open_risk_before']})",
        f"- Paths after: {proof['paths_after']} (risk {proof['open_risk_after']})",
        f"- Toxic combination still present: {'yes' if proof['toxic_after'] else 'no'}",
    ]
    rt = proof.get("redteam_after")
    if rt:
        lines += [f"- Red-team canary attacks that completed against the patched config: "
                  f"**{rt['completed']} of {rt['attacks']}** "
                  f"(before the patch: {proof['redteam_before']['completed']} of "
                  f"{proof['redteam_before']['attacks']})"]
    lines += ["", "### Trade-offs", "",
              "Gated tools will now ask a human before running. If a gate is too disruptive, "
              "re-plan with `keep_ungated` for that tool and BlastRadius will pick a scoped "
              "token or a different cut.", "",
              "_Generated by BlastRadius. All figures were measured on the real graph._"]
    return "\n".join(lines)


def _why(f) -> str:
    return {
        "gate": "Stops the agent acting on injected instructions without a human.",
        "scope": "Removes the tool's permission to reach that destination.",
        "remove_tool": "Removes the only route for that content to reach the agent.",
    }[f.action]
